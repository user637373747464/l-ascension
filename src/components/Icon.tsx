export type IconName = keyof typeof grids

const BOX = 11

const pathCache = new Map<IconName, { d: string; x: number; y: number; w: number; h: number }>()

function build(name: IconName) {
  const cached = pathCache.get(name)
  if (cached) return cached
  const grid = grids[name]
  const w = grid[0].length
  const h = grid.length
  const parts: string[] = []
  grid.forEach((row, y) => {
    let x = 0
    while (x < w) {
      if (row[x] === '#') {
        const start = x
        while (x < w && row[x] === '#') x += 1
        parts.push(`M${start} ${y}h${x - start}v1h-${x - start}z`)
      } else x += 1
    }
  })
  const entry = { d: parts.join(''), x: Math.floor((BOX - w) / 2), y: Math.floor((BOX - h) / 2), w, h }
  pathCache.set(name, entry)
  return entry
}

/**
 * The icon sits on a square 11 × 11 pixel grid. `size` is a rough width in CSS pixels:
 * it is rounded to a whole number of CSS pixels per icon pixel so the edges stay sharp.
 */
export function Icon({ name, size = 20, ...props }: SVGProps<SVGSVGElement> & { name: IconName; size?: number }) {
  const { d, x, y } = build(name)
  const side = Math.max(1, Math.round(size / 10)) * BOX
  return (
    <svg className="px-icon" width={side} height={side} viewBox={`0 0 ${BOX} ${BOX}`} fill="currentColor" shapeRendering="crispEdges" aria-hidden="true" {...props}>
      <path d={d} transform={`translate(${x} ${y})`} />
    </svg>
  )
}
